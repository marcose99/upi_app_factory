def load_json_object(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"Expected JSON object: {path}")
    return value


def main_worktree(project_root: Path) -> Path:
    output = subprocess.check_output(
        ["git", "-C", str(project_root), "worktree", "list", "--porcelain"],
        text=True,
    )
    current: Path | None = None
    for line in output.splitlines():
        if line.startswith("worktree "):
            current = Path(line.split(" ", 1)[1]).resolve()
        elif line == "branch refs/heads/main" and current is not None:
            return current
    branch = subprocess.check_output(
        ["git", "-C", str(project_root), "branch", "--show-current"],
        text=True,
    ).strip()
    if branch == "main":
        return project_root
    raise ValueError("Clean main worktree was not found")


def provision_prerequisites(project_root: Path) -> list[dict[str, Any]]:
    manifest = load_json_object(
        project_root / "config/autonomous/prerequisite_artifact_manifest.json"
    )
    artifacts = manifest.get("artifacts")
    if not isinstance(artifacts, list):
        raise ValueError("Prerequisite artifacts must be a list")
    source_root = main_worktree(project_root)
    records: list[dict[str, Any]] = []
    for item in artifacts:
        if not isinstance(item, dict):
            raise ValueError("Prerequisite entry must be an object")
        relative = item.get("path")
        expected = item.get("sha256")
        if not isinstance(relative, str) or not isinstance(expected, str):
            raise ValueError("Prerequisite path and hash are required")
        source = source_root / relative
        target = project_root / relative
        if not source.is_file():
            raise ValueError(f"Prerequisite source is missing: {relative}")
        if hashlib.sha256(source.read_bytes()).hexdigest() != expected:
            raise ValueError(f"Prerequisite hash mismatch: {relative}")
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        if hashlib.sha256(target.read_bytes()).hexdigest() != expected:
            raise ValueError(f"Prerequisite copy mismatch: {relative}")
        records.append({"path": relative, "sha256": expected})
    return records


def validate_content(relative: str, path: Path) -> None:
    if relative.endswith(".py"):
        py_compile.compile(str(path), doraise=True)
    elif relative.endswith(".json"):
        value = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(value, dict):
            raise ValueError(f"JSON payload must be an object: {relative}")


def install(phase: str, project_root: Path) -> dict[str, Any]:
    if phase not in PHASE_PAYLOADS:
        raise ValueError(f"Unsupported phase: {phase}")
    prerequisites = provision_prerequisites(project_root)
    staging = project_root / f".phase{phase.lower()}_payload_staging"
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)
    records: list[dict[str, Any]] = []
    payload = PHASE_PAYLOADS[phase]
    for relative, content in sorted(payload.items()):
        staged = staging / relative
        staged.parent.mkdir(parents=True, exist_ok=True)
        staged.write_text(content, encoding="utf-8")
        validate_content(relative, staged)
        records.append(
            {
                "path": relative,
                "sha256": hashlib.sha256(staged.read_bytes()).hexdigest(),
                "size": staged.stat().st_size,
            }
        )
    for relative in sorted(payload):
        staged = staging / relative
        destination = project_root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        temporary = destination.with_suffix(destination.suffix + ".payload.tmp")
        temporary.write_bytes(staged.read_bytes())
        os.replace(temporary, destination)
    shutil.rmtree(staging)
    return {
        "status": "PASSED",
        "phase": phase,
        "written_file_count": len(records),
        "written_files": records,
        "prerequisite_count": len(prerequisites),
        "llm_calls": 0,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["install"])
    parser.add_argument("--phase", required=True)
    parser.add_argument("--project-root", type=Path, required=True)
    parsed = parser.parse_args()
    report = install(parsed.phase, parsed.project_root.resolve())
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
